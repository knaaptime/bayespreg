r"""Normal-mixture approximations to :math:`-\log \operatorname{Gamma}(\nu, 1)`.

The auxiliary-mixture augmentation of Frühwirth-Schnatter & Wagner (2006) turns
each Poisson observation into a location model whose error is
:math:`-\log \operatorname{Gamma}(\nu, 1)`; approximating that error by a finite
normal mixture is what makes the conditional model Gaussian.

These tables were **fitted numerically** by minimising KL divergence against the
exact density

.. math::

    f(x) = \exp(-\nu x - e^{-x}) / \Gamma(\nu)

on a fine grid, rather than transcribed from the published tables — which makes
the approximation error a measured quantity rather than an assumed one.  See
``test_poisson_mixture.py``, which re-derives the exact density from scratch and
asserts the error bounds quoted here.

Three regimes
-------------
``1 <= nu <= 30`` (integer)
    Per-:math:`\nu` tables, 10/8/6 components.  Worst KL ``2.4e-06``.
``30 < nu <= 2000``
    The standardised density depends on :math:`\nu` essentially only through its
    skew :math:`\sim 1/\sqrt{\nu}`, so a 4-component *standardised* mixture is
    tabulated on a log-spaced grid and interpolated in :math:`1/\sqrt{\nu}`; the
    exact mean :math:`-\psi(\nu)` and standard deviation
    :math:`\sqrt{\psi'(\nu)}` are restored analytically, so only the shape is
    approximated.  Worst interpolated KL ``1.9e-06``.

    The grid is fitted by **continuation** (each :math:`\nu` warm-started from
    the previous), which is load-bearing: independently fitted grid points land
    in different local optima whose components play different roles, and
    interpolating between those is meaningless — it measured KL ``2.1e-04``,
    and beyond :math:`\nu \approx 5000` was worse than using no mixture at all.
``nu > 2000``
    A single normal, :math:`N(-\psi(\nu), \psi'(\nu))`.  KL ``4.2e-05`` at the
    cutoff, falling as :math:`1/\nu`.

The single-normal limit is adequate *only* this far out: at :math:`\nu = 30` it
is ``2.8e-03``, four orders of magnitude worse than the tabulated mixture, so
counts in the tens must not be routed to it.
"""

