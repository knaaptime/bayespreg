_SMALL_CACHE: dict[int, tuple[np.ndarray, np.ndarray, np.ndarray]] = {}


def mixture_for_unit_shape() -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    r"""Mixture for :math:`-\log \operatorname{Exp}(1)`, i.e. shape 1.

    This is the inter-arrival branch, shared by every observation regardless of
    its count, so it is worth its own entry point.  (It is exactly a standard
    Gumbel distribution.)

    Returns
    -------
    w, m, v : ndarray
        Weights, means and **variances** of the mixture components.
    """
    return mixture_for_shape(1.0)


def mixture_for_shape(nu: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    r"""Normal-mixture approximation to :math:`-\log \operatorname{Gamma}(\nu, 1)`.

    Parameters
    ----------
    nu : float
        Shape parameter — the count :math:`y_i` on the last-arrival branch.

    Returns
    -------
    w, m, v : ndarray
        Weights, means and **variances**.  A length-1 result means the caller
        can skip the mixture-indicator draw entirely.
    """
    nu = float(nu)
    if nu <= 0:
        raise ValueError(f"shape must be positive, got {nu}")

    key = int(nu)
    if key == nu and 1 <= key <= _MAX_INT_SHAPE:
        hit = _SMALL_CACHE.get(key)
        if hit is None:
            w, m, s = _SMALL[key]
            hit = (np.array(w), np.array(m), np.array(s) ** 2)
            _SMALL_CACHE[key] = hit
        return hit

    mean = -digamma(nu)
    sd = np.sqrt(polygamma(1, nu))

    if nu > MAX_TABULATED_SHAPE:
        # Skew ~ 1/sqrt(nu) is negligible; one normal suffices and the
        # indicator draw disappears.
        return (np.array([1.0]), np.array([mean]), np.array([sd**2]))

    x = 1.0 / np.sqrt(nu)
    k = _LG_WS.shape[1]
    w = np.array([np.interp(x, _LG_XS, _LG_WS[:, j]) for j in range(k)])
    m = np.array([np.interp(x, _LG_XS, _LG_MS[:, j]) for j in range(k)])
    s = np.array([np.interp(x, _LG_XS, _LG_SS[:, j]) for j in range(k)])
    w = w / w.sum()
    # Un-standardise: exact mean and sd, approximated shape.
    return w, mean + sd * m, (sd * s) ** 2
